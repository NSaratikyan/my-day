export function zodiacForBirthday(birthday: string) {
  if (!birthdaySchema.safeParse(birthday).success) return undefined;
  const day = birthday.slice(5);
  if (day >= "12-22") return zodiacSigns[0];
  return [...zodiacSigns].reverse().find(sign => day >= sign.start) ?? zodiacSigns[0];
}

export function dailyHoroscope(birthday: string, date: string) {
  const sign = zodiacForBirthday(birthday);
  if (!sign) return undefined;
  // UTC here is only a day ordinal from local date components: never convert
  // the current instant to UTC, so midnight and DST cannot shift the advice.
  const [year, month, day] = date.split("-").map(Number);
  const ordinal = Math.floor(Date.UTC(year, month - 1, day) / 86400000);
  const index = zodiacSigns.indexOf(sign);
  const pick = (ordinal + index * 7) % advice.length;
  return { sign, text: advice[(pick + advice.length) % advice.length], focus: sign.focus };
}
